def slugify(value: str) -> str:
    text = re.sub(r"[^a-z0-9\u4e00-\u9fff]+", "-", value.strip().lower())
    return re.sub(r"-{2,}", "-", text).strip("-") or "pm-case"


def write_if_missing(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        # 独占创建可避免重复初始化覆盖用户编辑，也避免检查后写入的竞争窗口。
        with path.open("x", encoding="utf-8") as output:
            output.write(content)
    except FileExistsError:
        if not path.is_file() or path.is_symlink():
            raise ValueError(f"目标不是普通文件：{path}")


def check_existing_case(root: Path, title: str, profile: str) -> None:
    manifest_path = root / "feishu/manifest.json"
    if not manifest_path.exists():
        return
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeError) as exc:
        raise ValueError("已有 manifest.json 无法读取，请检查内容或改用新目录") from exc
    if not isinstance(manifest, dict):
        raise ValueError("已有 manifest.json 必须是 JSON 对象")
    # 旧版清单没有 profile，按原先唯一的 standard 模式兼容。
    if manifest.get("project_title") != title:
        raise ValueError("目录已有其他标题的项目，请使用 --nested 或新的 --base-dir")
    if manifest.get("profile", "standard") != profile:
        raise ValueError("目录已有不同交付模式，请使用新的 --base-dir，避免混合清单")


def initialize_case(root: Path, title: str, slug: str, profile: str) -> None:
    check_existing_case(root, title, profile)
    documents = DOCS if profile == "standard" else LEAN_DOCS
    files = {
        "brief/00-request.md": (
            f"# 原始需求\n\n- 标题：{title}\n- 交付模式：{profile}\n"
            "- 原始输入/来源：待补充\n- 使用/决策/付费角色：待补充\n"
            "- 核心问题与目标：待补充\n- 成功口径与约束：待补充\n"
            "- 原型/汇报/发布范围及授权：待明确\n"
        ),
        **COMMON_TEMPLATES,
        "feishu/publish-plan.md": "# 飞书发布计划\n\n状态：未要求发布。仅在已有明确授权后执行。\n",
        "feishu/publish-result.md": "# 飞书发布结果\n\n状态：未发布。\n",
    }
    for name, _ in documents:
        files[f"prd/{name}"] = (
            DOC_TEMPLATES[name] if profile == "standard" else LEAN_TEMPLATE
        )
    if profile == "standard":
        files.update(STANDARD_EXTRAS)
        files["deck/02-deck-spec.json"] = json.dumps(
            {
                "title": title,
                "author": "PD Skill",
                "footerText": "Generated by pd",
                "slides": [],
            },
            ensure_ascii=False,
            indent=2,
        ) + "\n"

    # 在写入前检查受控路径，避免通过已有符号链接把模板写到案例目录外。
    for relative_path in [*files, "feishu/manifest.json"]:
        target = root / relative_path
        for candidate in [target, *target.parents]:
            if candidate == root:
                break
            if candidate.is_symlink():
                raise ValueError(f"案例路径含符号链接，请改用普通目录：{candidate}")
    for relative_path, content in files.items():
        write_if_missing(root / relative_path, content)

    manifest = {
        "project_title": title,
        "slug": slug,
        "profile": profile,
        "folder_name": f"PRD - {title}",
        "documents": [
            {"title": doc_title, "path": str((root / "prd" / name).resolve())}
            for name, doc_title in documents
        ],
    }
    # 发布清单可能已有人工筛选、远端链接或 token，同样只能补缺失文件。
    write_if_missing(
        root / "feishu/manifest.json",
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="初始化产品经理交付骨架，不覆盖已有文件")
    parser.add_argument("--title", required=True, help="项目或需求标题")
    parser.add_argument("--slug", help="目录名，仅限英文、数字、中文、连字符和下划线")
    parser.add_argument("--base-dir", default=".pd", help="输出路径，默认当前目录下的 .pd/")
    parser.add_argument("--nested", action="store_true", help="在 base-dir 下追加 slug 子目录")
    parser.add_argument(
        "--profile",
        choices=("standard", "lean"),
        default="standard",
        help="standard：19 篇 PRD；lean：1 篇功能规格",
    )
    args = parser.parse_args()
    title = args.title.strip()
    if not title or any(ord(char) < 32 for char in title):
        parser.error("标题不能为空或包含换行/控制字符")
    slug = args.slug if args.slug is not None else slugify(title)
    if not re.fullmatch(r"[a-zA-Z0-9\u4e00-\u9fff_-]+", slug):
        parser.error("slug 只能包含英文、数字、中文、连字符和下划线，不能包含路径分隔符")
    try:
        base_dir = Path(args.base_dir).expanduser().resolve()
        root = base_dir / slug if args.nested else base_dir
        if root.is_symlink():
            raise ValueError("嵌套案例目录不能是符号链接")
        initialize_case(root, title, slug, args.profile)
    except (OSError, ValueError) as exc:
        parser.exit(2, f"初始化失败：{exc}\n")
    print(root)


if __name__ == "__main__":
    main()
